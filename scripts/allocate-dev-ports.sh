#!/usr/bin/env bash
# Allocate per-worktree host ports for parallel `dev` stacks / manual-test.
# Writes repo-root `.env.tilt.ports` (gitignored). Idempotent when the file exists
# and still belongs to this worktree.
#
# Slot N → APP_PORT=3000+N, FRONTEND_PORT=8080+N (N = 0..31).
# Claims live under a per-user cache dir so two worktrees cannot pick the same
# free ports while cargo build has not bound them yet.
# At most LIFE_MANAGER_MAX_PARALLEL_DEV_STACKS (default 2) live claims may exist.
# Control-agent reads the slot with: grep -oP 'for slot \K[0-9]+' .env.tilt.ports
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$REPO_ROOT/.env.tilt.ports"
MAX_SLOT="${DEV_PORT_MAX_SLOT:-31}"
MAX_PARALLEL_DEV_STACKS="${LIFE_MANAGER_MAX_PARALLEL_DEV_STACKS:-2}"
FORCE="${1:-}"
CLAIM_UID="${UID:-$(id -u)}"
DEFAULT_CLAIM_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/life-manager/dev-port-claims"
CLAIM_DIR="${LIFE_MANAGER_PORT_CLAIM_DIR:-$DEFAULT_CLAIM_DIR}"
LOCK_FILE="${CLAIM_DIR}/allocate.lock"
# Set when --force clears this worktree's existing claim so re-slot stays allowed.
REPLACING_OWN_STACK=0

ensure_claim_dir() {
  mkdir -p -m 700 "$CLAIM_DIR"
  if [[ -L "$CLAIM_DIR" ]]; then
    echo "Error: claim dir must not be a symlink: $CLAIM_DIR" >&2
    exit 1
  fi
  if [[ ! -d "$CLAIM_DIR" ]]; then
    echo "Error: claim dir is not a directory: $CLAIM_DIR" >&2
    exit 1
  fi
  local owner
  owner="$(stat -c '%u' "$CLAIM_DIR" 2>/dev/null || stat -f '%u' "$CLAIM_DIR")"
  if [[ "$owner" != "$CLAIM_UID" ]]; then
    echo "Error: claim dir not owned by uid $CLAIM_UID: $CLAIM_DIR" >&2
    exit 1
  fi
}

ensure_claim_dir

port_free() {
  local port="$1"
  if command -v ss >/dev/null 2>&1; then
    ! ss -ltn | grep -qE ":${port}[[:space:]]"
  elif command -v lsof >/dev/null 2>&1; then
    ! lsof -ti ":${port}" -sTCP:LISTEN >/dev/null 2>&1
  else
    return 0
  fi
}

claim_path() {
  echo "${CLAIM_DIR}/slot-$1.claim"
}

# Read claim as plain KEY=value lines. Do not source (claim files are data).
read_claim_field() {
  local slot="$1" key="$2" f line
  f="$(claim_path "$slot")"
  [[ -f "$f" ]] || return 1
  line="$(grep -E "^${key}=" "$f" | head -n1 || true)"
  [[ -n "$line" ]] || return 1
  echo "${line#${key}=}"
}

# Reclaim only when the claiming worktree directory is gone (or claim is empty).
claim_is_releasable() {
  local slot="$1"
  local root
  root="$(read_claim_field "$slot" WORKTREE_ROOT 2>/dev/null || true)"
  [[ -n "$root" ]] || return 0
  if [[ ! -d "$root" ]]; then
    return 0
  fi
  return 1
}

# Count claims whose worktree directory still exists.
count_live_claims() {
  local count=0
  local f root
  shopt -s nullglob
  for f in "$CLAIM_DIR"/slot-*.claim; do
    root="$(grep -E '^WORKTREE_ROOT=' "$f" | head -n1 | cut -d= -f2- || true)"
    if [[ -n "$root" && -d "$root" ]]; then
      count=$((count + 1))
    fi
  done
  shopt -u nullglob
  echo "$count"
}

worktree_has_live_claim() {
  local f root
  shopt -s nullglob
  for f in "$CLAIM_DIR"/slot-*.claim; do
    root="$(grep -E '^WORKTREE_ROOT=' "$f" | head -n1 | cut -d= -f2- || true)"
    if [[ "$root" == "$REPO_ROOT" && -d "$root" ]]; then
      shopt -u nullglob
      return 0
    fi
  done
  shopt -u nullglob
  return 1
}

list_live_claim_roots() {
  local f root
  shopt -s nullglob
  for f in "$CLAIM_DIR"/slot-*.claim; do
    root="$(grep -E '^WORKTREE_ROOT=' "$f" | head -n1 | cut -d= -f2- || true)"
    if [[ -n "$root" && -d "$root" ]]; then
      printf '  - %s\n' "$root"
    fi
  done
  shopt -u nullglob
}

# Allow restart/re-slot for this worktree. Block a third new stack.
assert_may_allocate_new_stack() {
  local live
  if (( REPLACING_OWN_STACK == 1 )); then
    return 0
  fi
  if worktree_has_live_claim; then
    return 0
  fi
  live="$(count_live_claims)"
  if (( live < MAX_PARALLEL_DEV_STACKS )); then
    return 0
  fi
  echo "Error: already ${live} live host dev stack claim(s); max is ${MAX_PARALLEL_DEV_STACKS}." >&2
  echo "Free a worktree or claim before starting another full stack." >&2
  echo "Override only when needed: LIFE_MANAGER_MAX_PARALLEL_DEV_STACKS=<n>" >&2
  echo "Live claims:" >&2
  list_live_claim_roots >&2
  exit 1
}

write_claim() {
  local slot="$1"
  local now tmp target
  now="$(date +%s)"
  target="$(claim_path "$slot")"
  tmp="$(mktemp "${CLAIM_DIR}/slot-${slot}.claim.XXXXXX")"
  {
    printf 'WORKTREE_ROOT=%s\n' "$REPO_ROOT"
    printf 'CLAIMED_AT=%s\n' "$now"
  } >"$tmp"
  mv -f "$tmp" "$target"
}

clear_claim_if_ours() {
  local slot="$1"
  local root
  root="$(read_claim_field "$slot" WORKTREE_ROOT 2>/dev/null || true)"
  if [[ -n "$root" && "$root" == "$REPO_ROOT" ]]; then
    rm -f "$(claim_path "$slot")"
  fi
}

write_ports() {
  local slot="$1"
  local app=$((3000 + slot))
  local fe=$((8080 + slot))
  assert_may_allocate_new_stack
  write_claim "$slot"
  cat >"$OUT" <<EOF
# Dev port assignment for slot ${slot} (parallel worktrees / manual-test)
# Generated by scripts/allocate-dev-ports.sh — do not commit.
APP_PORT=${app}
FRONTEND_PORT=${fe}
EXPO_PUBLIC_API_BASE_URL=http://localhost:${app}
EOF
  echo "Wrote $OUT (slot ${slot}: APP_PORT=${app} FRONTEND_PORT=${fe})"
}

reuse_existing_slot() {
  local slot="$1"
  local app=$((3000 + slot))
  local fe=$((8080 + slot))
  write_claim "$slot"
  echo "Using existing $OUT (slot ${slot}: APP_PORT=${app} FRONTEND_PORT=${fe})"
}

slot_available() {
  local slot="$1"
  local app=$((3000 + slot))
  local fe=$((8080 + slot))
  local root

  if ! port_free "$app" || ! port_free "$fe"; then
    return 1
  fi

  root="$(read_claim_field "$slot" WORKTREE_ROOT 2>/dev/null || true)"
  if [[ -z "$root" || "$root" == "$REPO_ROOT" ]]; then
    return 0
  fi

  # Foreign claim: hold while the worktree directory exists (covers cargo build).
  if claim_is_releasable "$slot"; then
    rm -f "$(claim_path "$slot")"
    return 0
  fi
  return 1
}

read_slot_from_ports_file() {
  local app
  app="$(grep -E '^APP_PORT=' "$OUT" | head -n1 | cut -d= -f2- || true)"
  [[ -n "$app" && "$app" =~ ^[0-9]+$ ]] || return 1
  echo $((app - 3000))
}

# Serialize allocates so claims are visible before the next worktree chooses.
exec 9>"$LOCK_FILE"
if ! flock -w 30 9; then
  echo "Error: could not lock $LOCK_FILE" >&2
  exit 1
fi

if [[ -f "$OUT" && "$FORCE" != "--force" ]]; then
  slot="$(read_slot_from_ports_file || true)"
  if [[ -n "${slot:-}" ]]; then
    root="$(read_claim_field "$slot" WORKTREE_ROOT 2>/dev/null || true)"
    app=$((3000 + slot))
    fe=$((8080 + slot))
    ports_busy=0
    if ! port_free "$app" || ! port_free "$fe"; then
      ports_busy=1
    fi

    # Own claim, or no claim: keep this file (rewrite claim). Busy ports usually
    # mean this worktree's stack is still up after a claim-dir move or cache clear.
    if [[ -z "$root" || "$root" == "$REPO_ROOT" ]]; then
      reuse_existing_slot "$slot"
      exit 0
    fi

    if (( ports_busy == 0 )) && claim_is_releasable "$slot"; then
      write_ports "$slot"
      exit 0
    fi

    echo "Existing $OUT slot ${slot} is reserved or in use; allocating a new slot..."
  fi
fi

if [[ "$FORCE" == "--force" && -f "$OUT" ]]; then
  old_slot="$(read_slot_from_ports_file || true)"
  if [[ -n "${old_slot:-}" ]]; then
    root="$(read_claim_field "$old_slot" WORKTREE_ROOT 2>/dev/null || true)"
    if [[ -n "$root" && "$root" == "$REPO_ROOT" ]]; then
      REPLACING_OWN_STACK=1
    fi
    clear_claim_if_ours "$old_slot"
  fi
fi

for slot in $(seq 0 "$MAX_SLOT"); do
  if slot_available "$slot"; then
    write_ports "$slot"
    exit 0
  fi
done

echo "Error: no free port slot in 0..${MAX_SLOT} (tried APP_PORT 3000+n / FRONTEND_PORT 8080+n)" >&2
exit 1
